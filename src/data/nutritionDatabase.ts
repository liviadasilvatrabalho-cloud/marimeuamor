/**
 * Pure mathematical calculation:
 * Given food values per 100g and a target portion in grams,
 * calculate exact nutritional macros.
 */
export function calculateNutritionalValues(
  food: {
    caloriesPer100g: number;
    proteinPer100g: number;
    carbsPer100g: number;
    fatPer100g: number;
    fiberPer100g: number;
  },
  portionGrams: number
) {
  const ratio = Math.max(0, portionGrams) / 100;
  return {
    portionGrams: Math.round(portionGrams * 10) / 10,
    calories: Math.round(food.caloriesPer100g * ratio),
    protein: Math.round(food.proteinPer100g * ratio * 10) / 10,
    carbs: Math.round(food.carbsPer100g * ratio * 10) / 10,
    fat: Math.round(food.fatPer100g * ratio * 10) / 10,
    fiber: Math.round(food.fiberPer100g * ratio * 10) / 10,
  };
}
